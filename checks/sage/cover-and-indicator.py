"""Bounded exact counterexamples for the metacyclic cover and invariant c.

The cover check is for D8; a cyclic C12 example tests the root constraint
in the adjacent metacyclic multiplier calculation (Theorem 11.43).
The invariant check is for two dual linear C3 modules (Proposition 12.11).
Neither check proves a general cover construction or indicator theorem.
"""
from itertools import product
from sage.all import CyclotomicField

checked = []


def check(name, condition):
    assert condition, name
    checked.append(name)


identity = (0, 0, 0)
elements = set(product(range(4), range(2), range(2)))


def multiply(left, right):
    a, c, b = left
    x, y, d = right
    return ((a + (-1)**b*x) % 4, (c+y+b*x) % 2, (b+d) % 2)


def power(value, exponent, operation=multiply, one=identity):
    result = one
    for _ in range(exponent):
        result = operation(result, value)
    return result


def generated(generators, operation=multiply, one=identity):
    result = {one}
    while True:
        larger = result | {operation(g, h) for g in result for h in generators}
        if larger == result:
            return result
        result = larger


check('sixteen elements closed',
      all(multiply(g, h) in elements for g in elements for h in elements))
check('associativity on every triple',
      all(multiply(multiply(g, h), k) == multiply(g, multiply(h, k))
          for g in elements for h in elements for k in elements))
check('identity', all(multiply(g, identity) == multiply(identity, g) == g
                      for g in elements))
inverses = {g: next(h for h in elements
                   if multiply(g, h) == multiply(h, g) == identity)
            for g in elements}
check('all inverses', len(inverses) == 16)
a, b, c = (1, 0, 0), (0, 0, 1), (0, 1, 0)
check('presentation powers',
      power(a, 4) == power(b, 2) == power(c, 2) == identity)
check('presentation conjugation',
      multiply(multiply(b, a), inverses[b]) == multiply(c, inverses[a]))
check('central c', all(multiply(c, g) == multiply(g, c) for g in elements))
check('presentation generates every element', generated({a, b, c}) == elements)
commutators = {multiply(multiply(multiply(inverses[g], inverses[h]), g), h)
               for g in elements for h in elements}
derived = generated(commutators)
check('derived group is generated by ca squared',
      derived == {identity, multiply(c, power(a, 2))})


def dihedral(left, right, degree=4):
    x, e = left
    y, f = right
    return ((x + (-1)**e*y) % degree, (e+f) % 2)


def quotient(value):
    return (value[0], value[2])


check('map onto D8 preserves every product',
      len({quotient(g) for g in elements}) == 8
      and all(quotient(multiply(g, h)) == dihedral(quotient(g), quotient(h))
              for g in elements for h in elements))
kernel = {g for g in elements if quotient(g) == (0, 0)}
check('order two kernel fails stem criterion',
      kernel == {identity, c} and not kernel <= derived)
cover = set(product(range(8), range(2)))
operation = lambda g, h: dihedral(g, h, 8)
one = (0, 0)
cover_inverses = {g: next(h for h in cover
                         if operation(g, h) == operation(h, g) == one)
                  for g in cover}
cover_derived = generated(
    {operation(operation(operation(cover_inverses[g], cover_inverses[h]), g), h)
     for g in cover for h in cover}, operation, one)
cover_kernel = {(0, 0), (4, 0)}
check('D16 maps onto D8',
      all(dihedral((g[0] % 4, g[1]), (h[0] % 4, h[1]))
          == (operation(g, h)[0] % 4, operation(g, h)[1])
          for g in cover for h in cover))
check('D16 kernel is central and lies in derived group',
      cover_kernel <= cover_derived
      and all(operation(g, h) == operation(h, g)
              for g in cover_kernel for h in cover))
fourth_root = CyclotomicField(4).gen()
mu_four = {fourth_root**i for i in range(4)}
mu_two = {fourth_root**i for i in (0, 2)}
quotient_cosets = {frozenset(z*h for h in mu_two) for z in mu_four}
check('root quotient has order two', len(quotient_cosets) == len(cover_kernel))
check('order two root does not represent the nontrivial quotient class',
      frozenset(-h for h in mu_two) == frozenset(mu_two)
      and frozenset(fourth_root*h for h in mu_two) != frozenset(mu_two))

# m=4,r=1,s=3,t=3: a=b^9 gives the cyclic group of order twelve.
check('cyclic twelve has all twelve metacyclic normal forms',
      len({(9*i+j) % 12 for i in range(4) for j in range(3)}) == 12
      and 9*4 % 12 == 0 and 3 % 12 == 9*3 % 12)
twelfth_root = CyclotomicField(12).gen()
printed_choices = {twelfth_root**(4*i) for i in range(3)}
admissible = {z for z in printed_choices if z**4 == z**3 == 1}
check('cube roots alone admit two inconsistent commutation parameters',
      len(printed_choices) == 3 and admissible == {twelfth_root**0})

field = CyclotomicField(3)
root = field.gen()


def invariant(character):
    # Invariant dimensions of S²M and Λ²M are their averaged characters.
    symmetric = sum((character(i)**2 + character(2*i))/2 for i in range(3))/3
    alternating = sum((character(i)**2 - character(2*i))/2 for i in range(3))/3
    return symmetric - alternating


linear = lambda i: root**(i % 3)
dual = lambda i: linear(-i)
check('two dual nontrivial linear modules have invariant zero',
      invariant(linear) == invariant(dual) == 0)
check('their tensor product has invariant one',
      invariant(lambda i: linear(i)*dual(i)) == 1)
check('invariant is additive on their direct sum',
      invariant(lambda i: linear(i)+dual(i))
      == invariant(linear)+invariant(dual))
print(f'{len(checked)} exact cover, cyclic-root and invariant checks passed')
